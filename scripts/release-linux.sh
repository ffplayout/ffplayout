#!/usr/bin/env bash
# Invoked by the release workflow inside its Debian or Ubuntu image, as root.
set -euo pipefail

export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y --no-install-recommends \
    binutils build-essential clang curl ca-certificates dpkg-dev gnupg \
    libavcodec-dev libavformat-dev libavutil-dev libclang-dev \
    libswresample-dev libswscale-dev pkg-config rpm
curl -fsSL https://deb.nodesource.com/setup_24.x | bash -
apt-get install -y --no-install-recommends nodejs

if ! command -v cargo >/dev/null 2>&1; then
    curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --profile minimal
    # Generated by rustup in the build container.
    # shellcheck source=/dev/null
    source "$HOME/.cargo/env"
fi

npm ci
cargo build --locked --release --no-default-features --features embed_frontend
cargo install cargo-deb --locked
bash scripts/package-deb.sh dist dynamic "$GITHUB_REF_NAME"

# Keep the existing RPM artifact on the Debian job only.
if [[ -n ${RPM_ARCH:-} ]]; then
    cargo install cargo-generate-rpm --locked
    package_version=$(printf '%s' "${GITHUB_REF_NAME#v}" | tr '-' '~')
    cargo generate-rpm -p crates/app \
        --set-metadata "version = \"$package_version\"" \
        --set-metadata 'release = "1"' \
        -o "dist/ffplayout-${GITHUB_REF_NAME}-1.${RPM_ARCH}.rpm"
fi
